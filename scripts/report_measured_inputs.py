def J(*p):
    with open(os.path.join(D, *p), encoding="utf-8") as f:
        return json.load(f)


def manifest():
    with open(os.path.join(ROOT, "data", "raw", "manifest.json"), encoding="utf-8") as f:
        m = json.load(f)
    return {e["file"]: e for e in m["entries"]}


def prov(man, prefix):
    rows = [e for k, e in man.items() if k.startswith(prefix)]
    if not rows:
        return "not pulled"
    first = min(e["pulled_utc"] for e in rows)[:10]
    return f"{len(rows)} file(s), pulled {first}, sha256 in manifest"


def gated_from_histogram(cab, range_m, minutes=(1, 2, 5, 10, 20)):
    """Duration-gated daytime contact rate from contact_durations.csv (older JSON lacks the field)."""
    import csv
    path = os.path.join(D, "cabspotting", "contact_durations.csv")
    if not os.path.exists(path):
        return {}
    hist = {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["range_m"] == range_m:
                hist[int(row["duration_bin_start_s"])] = int(row["events"])
    total = sum(hist.values())
    beta = cab["ranges"][f"{range_m}m"]["beta_per_min_daytime"]
    return {f"ge_{m}min": beta * sum(c for b, c in hist.items() if b >= 60 * m) / total for m in minutes} if total else {}


def sim_results():
    """T95 and S95 rows from the frozen reference run, if it exists: {(sweep, class, param, value, arch, metric): result}."""
    import csv
    path = os.path.join(ROOT, "expected", "sweeps_v4.csv")
    if not os.path.exists(path):
        return None
    out = {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            v = row["result"]
            out[(row["sweep"], row["class"], row["param"], row["value"], row["arch"], row["metric"])] = (None if v == "" else float(v))
    return out


def qrow(name, q, keys=("q10", "q25", "q50", "q75", "q90")):
    if q is None:
        return f"| {name} | " + " | ".join("n/a" for _ in keys) + " | n/a | n/a |"
    return f"| {name} | " + " | ".join(f"{q[k]:.0f}" for k in keys) + f" | {q['mean']:.0f} | {q['n']:,} |"


