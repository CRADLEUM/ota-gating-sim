#!/usr/bin/env python3
"""Write the measured-inputs evidence file for the paper from the derived data.

Every number in the output is read from a file under data/derived/ that a
derive_*.py script produced from a raw pull listed in data/raw/manifest.json.
Nothing is typed in by hand, so the paper's Table I can be regenerated and
checked against this file.

Usage
    python scripts/report_measured_inputs.py [--out PATH]

Default output: ../Fleet_Propagation/ipccc2026-short/03_evidence/MEASURED_INPUTS.md
"""
